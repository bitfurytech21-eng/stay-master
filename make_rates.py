#!/usr/bin/env python3
"""Generate data/rates.json — the nightly rate for every apartment type.

Why this exists
---------------
The site never published nightly rates, so every unit in the search read
"Rate on request" and no price was ever shown. This script produces an
explicit, per-unit rate table so search results can show a real price.

IMPORTANT — these are indicative published rates, not scraped ones.
No rate data exists in the source site, the scrape, or the repo. The numbers
below come from a documented model (city base rate x unit size factor) and are
meant to be reviewed and edited by the business. data/rates.json is the single
source of truth: change a number there and rebuild, and that unit's price
changes everywhere. Nothing here is invented at render time.

Model
-----
    nightly = city_base * size_factor, rounded to the nearest 5

    size_factor = 1 + 0.30 * (bedrooms - 1) + 0.008 * (sqm - 25)
                  clamped to [0.80, 2.60]

City base rates are EUR per night for a standard studio in that market.
"""

import json
import os

ROOT = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.join(ROOT, 'data', 'site.json')
OUT = os.path.join(ROOT, 'data', 'rates.json')

# Indicative base nightly rate (EUR) for a standard studio, per city.
CITY_BASE = {
    'london': 210,
    'rome': 165,
    'barcelona': 155,
    'athens': 120,
    'warsaw': 95,
    'hamburg': 130,
    'salzburg': 145,
    'tel-aviv': 175,
    'bat-yam': 110,
}

# Currency per city. Rates are quoted in the local market currency.
CITY_CURRENCY = {
    'london': 'GBP',
    'rome': 'EUR',
    'barcelona': 'EUR',
    'athens': 'EUR',
    'warsaw': 'PLN',
    'hamburg': 'EUR',
    'salzburg': 'EUR',
    'tel-aviv': 'ILS',
    'bat-yam': 'ILS',
}

# EUR -> local currency, so a GBP/PLN/ILS rate is a real conversion of the
# EUR base rather than a relabelled number.
EUR_TO_LOCAL = {
    'EUR': 1.0,
    'GBP': 0.85,
    'PLN': 4.30,
    'ILS': 4.00,
}


def size_factor(bedrooms, sqm):
    f = 1.0 + 0.30 * (max(int(bedrooms or 1), 1) - 1) + 0.008 * ((sqm or 25) - 25)
    return max(0.80, min(2.60, f))


def round_to_5(x):
    return int(round(x / 5.0) * 5)


def main():
    with open(SITE, encoding='utf-8') as fh:
        site = json.load(fh)

    out = {}
    for b in site['buildings']:
        city = b['city']
        base = CITY_BASE.get(city, 120)
        currency = CITY_CURRENCY.get(city, 'EUR')
        fx = EUR_TO_LOCAL.get(currency, 1.0)
        units = {}
        for name, guests, beds, baths, sqm in b['apts']:
            eur = base * size_factor(beds, sqm)
            local = round_to_5(eur * fx)
            units[name] = {
                'nightly': local,
                'currency': currency,
            }
        out[b['slug']] = units

    payload = {
        '_note': ('Indicative published nightly rates, generated by make_rates.py '
                  'from a documented city-base x size-factor model. No rate data '
                  'exists in the source site. Edit any number here and rebuild to '
                  'change that unit\'s price everywhere.'),
        'rates': out,
    }

    with open(OUT, 'w', encoding='utf-8') as fh:
        json.dump(payload, fh, ensure_ascii=False, indent=1)

    total = sum(len(v) for v in out.values())
    print('Wrote %s: %d properties, %d units priced'
          % (os.path.relpath(OUT, ROOT), len(out), total))


if __name__ == '__main__':
    main()
